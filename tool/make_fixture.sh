#!/usr/bin/env bash
# Generates the on-device integration-test source video and embeds it as a
# Dart byte list (kept out of the app bundle and out of git).
set -euo pipefail
cd "$(dirname "$0")/.."
tmp=$(mktemp -d)
# 1280x720 landscape, VFR timestamps, 44.1 kHz AAC: exercises scaling, Fit
# 9:16 framing, CFR conversion and audio resampling in the native engine.
ffmpeg -hide_banner -loglevel error -y \
  -f lavfi -i testsrc2=size=1280x720:rate=30:duration=3 \
  -f lavfi -i sine=frequency=440:sample_rate=44100:duration=3 \
  -vf "settb=1/90000,setpts='(N/30+if(eq(mod(N,3),0),0.011,0))/TB'" -fps_mode passthrough \
  -enc_time_base:v 1/90000 -video_track_timescale 90000 \
  -c:v libx264 -preset veryfast -b:v 4M -pix_fmt yuv420p -c:a aac -b:a 128k "$tmp/source.mp4"
python3 - "$tmp/source.mp4" integration_test/fixture_data.dart <<'PY'
import base64, sys
data = base64.b64encode(open(sys.argv[1], 'rb').read()).decode()
lines = [data[i:i+120] for i in range(0, len(data), 120)]
with open(sys.argv[2], 'w') as f:
    f.write('// GENERATED by tool/make_fixture.sh — do not edit.\n')
    f.write("const fixtureBase64 = ''\n")
    for l in lines:
        f.write(f"    '{l}'\n")
    f.write(';\n')
PY
rm -rf "$tmp"
echo "wrote integration_test/fixture_data.dart"
